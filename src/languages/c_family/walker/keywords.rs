/// C and C++ keywords that a parser never reports as identifiers in valid code.
/// C allows a few C++ keywords, such as `new`, as names; those stay out of this list.
const KEYWORDS: &[&str] = &[
    "alignas",
    "alignof",
    "asm",
    "auto",
    "bool",
    "break",
    "case",
    "catch",
    "char",
    "co_await",
    "co_return",
    "co_yield",
    "concept",
    "const",
    "const_cast",
    "consteval",
    "constexpr",
    "constinit",
    "continue",
    "decltype",
    "default",
    "do",
    "double",
    "dynamic_cast",
    "else",
    "enum",
    "explicit",
    "export",
    "extern",
    "float",
    "for",
    "friend",
    "goto",
    "if",
    "inline",
    "int",
    "long",
    "mutable",
    "noexcept",
    "nullptr",
    "operator",
    "register",
    "reinterpret_cast",
    "requires",
    "restrict",
    "return",
    "short",
    "signed",
    "sizeof",
    "static",
    "static_assert",
    "static_cast",
    "struct",
    "switch",
    "template",
    "thread_local",
    "typedef",
    "typeid",
    "typename",
    "union",
    "unsigned",
    "virtual",
    "void",
    "volatile",
    "while",
];

pub(super) fn is_keyword(name: &str) -> bool {
    KEYWORDS.contains(&name)
}
